using System;
using System.Collections.Generic;

namespace SageUserApi.Models
{
    /// <summary>One lead (Lead Records). Can* say what the signed-in user may do with it.</summary>
    public class LeadDto
    {
        public Guid Id { get; set; }
        public string LeadNumber { get; set; } = string.Empty;
        public Guid CompanyId { get; set; }
        public string CompanyName { get; set; } = string.Empty;
        public string ClientName { get; set; }
        public string ClientDesignation { get; set; }
        public string ClientEmail { get; set; }
        public string ClientPhone { get; set; }
        public string SecondaryClientName { get; set; }
        public string SecondaryClientDesignation { get; set; }
        public string SecondaryClientEmail { get; set; }
        public string SecondaryClientPhone { get; set; }
        public int? ProductId { get; set; }
        public string ProductName { get; set; }
        public int? SourceId { get; set; }
        public string SourceName { get; set; }
        public string Requirement { get; set; }
        public int StatusId { get; set; }
        /// <summary>OPEN, WARM, WON, LOST, HOLD or DISQUALIFIED.</summary>
        public string StatusCode { get; set; } = string.Empty;
        public string StatusName { get; set; } = string.Empty;
        public int TypeId { get; set; }
        public string TypeName { get; set; } = string.Empty;
        public Guid GeneratedById { get; set; }
        public string GeneratedByName { get; set; } = string.Empty;
        public Guid AssignedId { get; set; }
        public string AssignedName { get; set; } = string.Empty;
        public decimal? MonthlyExpectedRevenue { get; set; }
        public int? BillingCycleId { get; set; }
        public string BillingCycleName { get; set; }
        public DateOnly? NextFollowUpDate { get; set; }
        public DateOnly LeadDate { get; set; }
        public DateOnly? ClosingDate { get; set; }
        public string Remarks { get; set; }
        /// <summary>Days since the created date (India time).</summary>
        public int AgingDays { get; set; }
        /// <summary>The order made from this lead, if any.</summary>
        public Guid? SaleId { get; set; }
        public string SaleNumber { get; set; }
        public string CreatedByName { get; set; } = string.Empty;
        public DateTime CreatedAtUtc { get; set; }
        public DateTime? UpdatedAtUtc { get; set; }
        /// <summary>The creator or the creator's manager.</summary>
        public bool CanEdit { get; set; }
        /// <summary>CanEdit and a sales manager.</summary>
        public bool CanDelete { get; set; }
        /// <summary>A Won lead with no order yet, for CanEdit or the assigned person.</summary>
        public bool CanOrder { get; set; }
    }

    /// <summary>A value of an Admin-managed lead list (product, source, billing cycle).</summary>
    public class LeadListOption
    {
        public int Id { get; set; }
        public string Name { get; set; } = string.Empty;
    }

    /// <summary>A value of a fixed lead list (status, lead type).</summary>
    public class LeadFixedOption
    {
        public int Id { get; set; }
        public string Code { get; set; } = string.Empty;
        public string Name { get; set; } = string.Empty;
    }

    /// <summary>A sales user for the Lead Generated By / Assigned Person boxes and filters.</summary>
    public class SalesUserOption
    {
        public Guid Id { get; set; }
        public string Name { get; set; } = string.Empty;
        /// <summary>SalesPerson or SalesManager.</summary>
        public string Role { get; set; } = string.Empty;
        /// <summary>Only active people can be chosen on a lead; inactive ones stay in the filters.</summary>
        public bool IsActive { get; set; }
    }

    /// <summary>One figure of the lead dashboard (a status, a source, an aging bucket, a lead type or a product).</summary>
    public class LeadSummaryItem
    {
        public int Id { get; set; }
        public string Code { get; set; }
        public string Name { get; set; } = string.Empty;
        /// <summary>Leads.</summary>
        public int Total { get; set; }
        /// <summary>Won leads.</summary>
        public int Won { get; set; }
        /// <summary>Monthly expected revenue of the won leads (INR).</summary>
        public decimal Revenue { get; set; }
    }

    /// <summary>GET api/user/leads/summary: the Home dashboard (from dbo.usp_Lead_Summary).</summary>
    public class LeadSummary
    {
        public int TotalLeads { get; set; }
        public int WonLeads { get; set; }
        /// <summary>Won ÷ total leads, in % (2 decimals); 0 when there are no leads.</summary>
        public decimal ConversionRate { get; set; }
        /// <summary>Monthly expected revenue of the won leads, and the same × 12.</summary>
        public decimal WonRevenueMonthly { get; set; }
        public decimal WonRevenueAnnualized { get; set; }
        public List<LeadSummaryItem> Statuses { get; set; } = new List<LeadSummaryItem>();
        public List<LeadSummaryItem> Sources { get; set; } = new List<LeadSummaryItem>();
        public List<LeadSummaryItem> Aging { get; set; } = new List<LeadSummaryItem>();
        public List<LeadSummaryItem> Types { get; set; } = new List<LeadSummaryItem>();
        /// <summary>Won leads and their monthly revenue per product.</summary>
        public List<LeadSummaryItem> Products { get; set; } = new List<LeadSummaryItem>();
    }

    /// <summary>GET api/user/leads/options: the lists of the lead form and filters.</summary>
    public class LeadOptions
    {
        public List<LeadListOption> Products { get; set; } = new List<LeadListOption>();
        public List<LeadListOption> Sources { get; set; } = new List<LeadListOption>();
        public List<LeadListOption> BillingCycles { get; set; } = new List<LeadListOption>();
        public List<LeadFixedOption> Statuses { get; set; } = new List<LeadFixedOption>();
        public List<LeadFixedOption> Types { get; set; } = new List<LeadFixedOption>();
        public List<SalesUserOption> SalesUsers { get; set; } = new List<SalesUserOption>();
    }
}
