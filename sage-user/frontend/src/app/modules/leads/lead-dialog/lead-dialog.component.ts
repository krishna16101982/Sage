import { Component, OnInit, computed, effect, inject, input, output, signal, untracked } from '@angular/core';
import { FormsModule } from '@angular/forms';
import { Alert } from '../../../component/alert/alert';
import { ComboBox, type ComboOption } from '../../../component/combo-box/combo-box';
import { Modal } from '../../../component/modal/modal';
import { LeadsService } from '../../../services/leads/leads.service';
import { errorText } from '../../../services/rest/global-rest-service';
import type { Customer } from '../../../shared/interfaces/customer.interface';
import type { Lead, LeadInput, LeadOptions } from '../../../shared/interfaces/lead.interface';
import { today } from '../../../shared/utils/dates';
import { CustomerPicker } from '../../sales/sales-add/customer-picker/customer-picker.component';

const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
/** 10 digits, optionally after +91 or a leading 0 (spaces and dashes ignored): the same rule as the server. */
const PHONE = /^(?:\+91|0)?[0-9]{10}$/;

/** The form's fields (strings for inputs; ids for lists). */
interface LeadForm {
  clientName: string;
  clientDesignation: string;
  clientEmail: string;
  clientPhone: string;
  secondaryClientName: string;
  secondaryClientDesignation: string;
  secondaryClientEmail: string;
  secondaryClientPhone: string;
  productId: number | null;
  sourceId: number | null;
  requirement: string;
  statusId: number | null;
  typeId: number | null;
  generatedById: string | null;
  assignedId: string | null;
  monthlyExpectedRevenue: number | null;
  billingCycleId: number | null;
  nextFollowUpDate: string;
  leadDate: string;
  closingDate: string;
  remarks: string;
}

/**
 * New Lead / View lead / Edit lead dialog. The company is chosen (or added) on a new lead, then read-only. Lead Generated By
 * and Assigned Person are searchable boxes of active sales users (managers included).
 */
@Component({
  selector: 'app-lead-dialog',
  imports: [FormsModule, Alert, Modal, ComboBox, CustomerPicker],
  templateUrl: './lead-dialog.component.html',
  styles: [`
    .lead-form { max-height: min(72vh, 46rem); overflow-y: auto; padding: 1rem 1.25rem; }
    .lead-section { margin-top: 0.5rem; padding-top: 0.75rem; border-top: 1px solid var(--color-border);
                    font-size: 0.75rem; font-weight: 600; letter-spacing: 0.04em; text-transform: uppercase; color: var(--color-text-muted); }
    .lead-meta { font-size: 0.8125rem; color: var(--color-text-muted); }
  `],
})
export class LeadDialog implements OnInit {
  readonly mode = input<'new' | 'view' | 'edit'>('new');
  /** The lead to show or change (view / edit). */
  readonly lead = input<Lead | null>(null);
  readonly options = input.required<LeadOptions>();
  readonly closed = output<void>();
  /** The saved lead, with the message to show. */
  readonly saved = output<{ lead: Lead; message: string }>();
  /** View: the user asked to edit. */
  readonly editRequested = output<void>();

  private readonly service = inject(LeadsService);
  readonly company = signal<Customer | null>(null);
  readonly form = signal<LeadForm>(this.blank());
  readonly error = signal<string | null>(null);
  readonly busy = signal(false);
  readonly submitted = signal(false);

  readonly readOnly = computed(() => this.mode() === 'view');
  readonly title = computed(() =>
    this.mode() === 'new' ? 'New Lead' : `${this.mode() === 'edit' ? 'Edit lead' : 'Lead'} ${this.lead()?.leadNumber ?? ''}`);

  /** Active sales users, plus the lead's own people if they were switched off since. */
  readonly people = computed<ComboOption[]>(() => {
    const keep = new Set([this.lead()?.generatedById, this.lead()?.assignedId]);
    return this.options().salesUsers
      .filter((u) => u.isActive || keep.has(u.id))
      .map((u) => ({ id: u.id, label: u.name, hint: [u.role === 'SalesManager' ? 'Manager' : '', u.isActive ? '' : 'inactive'].filter(Boolean).join(', ') || undefined }));
  });

  readonly problems = computed(() => {
    const f = this.form();
    const p: string[] = [];
    if (this.mode() === 'new' && !this.company()) p.push('Choose the company, or add a new one.');
    for (const [who, email, phone] of [['client', f.clientEmail, f.clientPhone], ['secondary client', f.secondaryClientEmail, f.secondaryClientPhone]] as const) {
      if (email.trim() && !EMAIL.test(email.trim())) p.push(`Enter a valid ${who} email.`);
      if (phone.trim() && !PHONE.test(phone.replace(/[\s-]/g, ''))) p.push(`Enter a 10-digit ${who} contact number.`);
    }
    if (!f.statusId) p.push('Choose the lead status.');
    if (!f.typeId) p.push('Choose the lead type.');
    if (!f.generatedById) p.push('Choose who generated the lead.');
    if (!f.assignedId) p.push('Choose the assigned person.');
    if (f.monthlyExpectedRevenue !== null && f.monthlyExpectedRevenue < 0) p.push('Monthly expected revenue cannot be negative.');
    if (!f.leadDate) p.push('Enter the created date.');
    return p;
  });

  constructor() {
    // Choosing a company fills the empty client fields from it.
    effect(() => {
      const c = this.company();
      untracked(() => {
        if (!c || this.mode() !== 'new') return;
        this.form.update((f) => ({
          ...f,
          clientName: f.clientName || c.contactPerson || '',
          clientEmail: f.clientEmail || c.email || '',
          clientPhone: f.clientPhone || c.phone || '',
        }));
      });
    });
  }

  ngOnInit(): void {
    const l = this.lead();
    if (!l) return;
    this.form.set({
      clientName: l.clientName ?? '', clientDesignation: l.clientDesignation ?? '', clientEmail: l.clientEmail ?? '', clientPhone: l.clientPhone ?? '',
      secondaryClientName: l.secondaryClientName ?? '', secondaryClientDesignation: l.secondaryClientDesignation ?? '',
      secondaryClientEmail: l.secondaryClientEmail ?? '', secondaryClientPhone: l.secondaryClientPhone ?? '',
      productId: l.productId, sourceId: l.sourceId, requirement: l.requirement ?? '',
      statusId: l.statusId, typeId: l.typeId, generatedById: l.generatedById, assignedId: l.assignedId,
      monthlyExpectedRevenue: l.monthlyExpectedRevenue, billingCycleId: l.billingCycleId,
      nextFollowUpDate: l.nextFollowUpDate ?? '', leadDate: l.leadDate, closingDate: l.closingDate ?? '', remarks: l.remarks ?? '',
    });
  }

  private blank(): LeadForm {
    return {
      clientName: '', clientDesignation: '', clientEmail: '', clientPhone: '',
      secondaryClientName: '', secondaryClientDesignation: '', secondaryClientEmail: '', secondaryClientPhone: '',
      productId: null, sourceId: null, requirement: '',
      // Open / Self Working, as on the old form.
      statusId: 1, typeId: 1, generatedById: null, assignedId: null,
      monthlyExpectedRevenue: null, billingCycleId: null, nextFollowUpDate: '', leadDate: today(), closingDate: '', remarks: '',
    };
  }

  set<K extends keyof LeadForm>(field: K, value: LeadForm[K]): void {
    this.form.update((f) => ({ ...f, [field]: value }));
  }

  /** A list value turned off since stays visible on this lead. */
  listWith<T extends { id: number; name: string }>(list: T[], id: number | null, name: string | null | undefined): T[] {
    return id && !list.some((o) => o.id === id) ? [...list, { id, name: `${name ?? 'Value'} (off)` } as T] : list;
  }

  async save(): Promise<void> {
    this.submitted.set(true);
    if (this.readOnly() || this.problems().length > 0) return;
    const f = this.form();
    const text = (v: string) => v.trim() || undefined;
    const body: LeadInput = {
      customerId: this.mode() === 'new' ? this.company()!.id : this.lead()!.companyId,
      clientName: text(f.clientName), clientDesignation: text(f.clientDesignation), clientEmail: text(f.clientEmail), clientPhone: text(f.clientPhone),
      secondaryClientName: text(f.secondaryClientName), secondaryClientDesignation: text(f.secondaryClientDesignation),
      secondaryClientEmail: text(f.secondaryClientEmail), secondaryClientPhone: text(f.secondaryClientPhone),
      productId: f.productId, sourceId: f.sourceId, requirement: text(f.requirement),
      statusId: f.statusId!, typeId: f.typeId!, generatedById: f.generatedById!, assignedId: f.assignedId!,
      monthlyExpectedRevenue: f.monthlyExpectedRevenue === null || (f.monthlyExpectedRevenue as unknown) === '' ? null : Number(f.monthlyExpectedRevenue),
      billingCycleId: f.billingCycleId, nextFollowUpDate: f.nextFollowUpDate || null, leadDate: f.leadDate,
      closingDate: f.closingDate || null, remarks: text(f.remarks),
    };
    this.error.set(null);
    this.busy.set(true);
    try {
      const lead = this.mode() === 'new' ? await this.service.create(body) : await this.service.update(this.lead()!.id, body);
      this.saved.emit({ lead, message: this.mode() === 'new' ? `Lead ${lead.leadNumber} added.` : `Lead ${lead.leadNumber} saved.` });
    } catch (err) {
      this.error.set(errorText(err));
    } finally {
      this.busy.set(false);
    }
  }
}
